#!/usr/bin/env python3
"""cand_extend.py [min_modules] [max_instr]  -- add new shared-function groups to tools/mp9/data/cand2.json.

Same grouping as cand.py (asm from build/SSQE01/<module>/asm with branch labels masked, functions
without references to module-local symbols), but with configurable thresholds. Existing groups are
kept untouched, so hashes already used by src/REL/shared/g_<hash8>.cpp stay valid.
Needs a full `ninja` first (the asm is regenerated by the split step)."""
import collections, glob, hashlib, json, os, re, struct, sys

MIN_MODS = int(sys.argv[1]) if len(sys.argv) > 1 else 3
MAX_INSTR = int(sys.argv[2]) if len(sys.argv) > 2 else 120
BASE = 'build/SSQE01'
CAND = 'tools/mp9/data/cand2.json'

mods = sorted(os.listdir('config/SSQE01/rels'))
inst = collections.defaultdict(list)
for m in mods:
    d = open('orig/SSQE01/files/modules/' + m + '.rel', 'rb').read()
    num = struct.unpack('>I', d[:4])[0]
    syms = {}
    for l in open('config/SSQE01/rels/%s/symbols.txt' % m):
        r = re.match(r'(\S+) = [.]text:0x([0-9A-F]+); // type:function size:0x([0-9A-F]+)', l)
        if r:
            syms[r[1]] = (int(r[2], 16), int(r[3], 16))
    cur = None
    body = {}
    for f in glob.glob('%s/%s/asm/**/*.s' % (BASE, m), recursive=True):
        for l in open(f, errors='ignore'):
            mm = re.match(r'\.fn (\S+),', l)
            if mm:
                cur = mm[1]
                body[cur] = []
            elif cur and l.startswith('/*'):
                body[cur].append(re.sub(r'/\*.*?\*/\s*', '', l).strip())
            elif l.startswith('.endfn'):
                cur = None
    loc = re.compile(r'\b(?:fn|lbl|jumptable)_' + str(num) + r'_\w+')
    for n, ls in body.items():
        if n.startswith(('gap_', 'pad_', '_prolog', '_epilog', '_unresolved', '__', 'shared_')) or n not in syms:
            continue
        if len(ls) < 2 or len(ls) > MAX_INSTR:
            continue
        txt = '\n'.join(re.sub(r'\.L_[0-9A-F]+', '.L', l) for l in ls)
        if loc.search(txt):
            continue
        h = hashlib.sha1(txt.encode()).hexdigest()[:14]
        inst[h].append((m, n, syms[n][0], syms[n][1], ls))

cand = json.load(open(CAND))
have = set(g['h'] for g in cand)
have8 = set(g['h'][:8] for g in cand)
taken = set((it[0], it[2]) for g in cand for it in g['items'])
inst = {h: [x for x in v if (x[0], x[2]) not in taken] for h, v in inst.items()}
added = []
for h, v in inst.items():
    nm = len(set(x[0] for x in v))
    if nm < MIN_MODS or h in have or h[:8] in have8:
        continue
    added.append({'n': nm, 'ln': len(v[0][4]), 'h': h, 'asm': v[0][4],
                  'items': [(x[0], x[1], x[2], x[3]) for x in v]})
added.sort(key=lambda g: -g['n'])
json.dump(cand + added, open(CAND, 'w'))
print('new groups: %d   copies: %d   instructions: %d' % (
    len(added), sum(g['n'] for g in added), sum(g['n'] * g['ln'] for g in added)))
for lo, hi in (('0', '7'), ('8', 'f')):
    sel = [g for g in added if lo <= g['h'][0] <= hi]
    print('  hashes %s-%s: %d groups, %d copies' % (lo, hi, len(sel), sum(g['n'] for g in sel)))
